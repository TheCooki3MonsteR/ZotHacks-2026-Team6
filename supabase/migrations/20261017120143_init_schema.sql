-- Postgres enforces foreign keys by default, so there is no PRAGMA here and no
-- per-connection setup required.

-- People who use the app.
create table users (
    user_id    bigint generated by default as identity primary key,
    username   varchar(25)  not null unique,
    -- Store a password *hash* (e.g. bcrypt, ~60 chars), never the plaintext.
    password   varchar(255) not null,
    created_at timestamptz  not null default now()
);

-- The water fountains themselves. Ratings live in `ratings`, not here, because
-- a rating belongs to a user, not to the fountain.
create table water_fountains (
    fountain_id bigint generated by default as identity primary key,
    name        varchar(100) not null,
    latitude    numeric(9,6),
    longitude   numeric(9,6),
    description text         not null
);

-- One rating per user per fountain. The composite PRIMARY KEY enforces that.
create table ratings (
    user_id     bigint       not null,
    fountain_id bigint       not null,
    rating      numeric(2,1) not null,
    rated_at    timestamptz  not null default now(),
    primary key (user_id, fountain_id),
    constraint chk_rating check (rating >= 1 and rating <= 5),
    foreign key (user_id)     references users(user_id)               on delete cascade,
    foreign key (fountain_id) references water_fountains(fountain_id) on delete cascade
);

-- User <-> fountain visit relationship, with a count and the last-visit time.
-- "User clicks a fountain -> look it up here" is a lookup on this primary key.
create table user_visited (
    user_id       bigint      not null,
    fountain_id   bigint      not null,
    times_visited integer     not null default 1,
    last_visited  timestamptz not null default now(),
    primary key (user_id, fountain_id),
    foreign key (user_id)     references users(user_id)               on delete cascade,
    foreign key (fountain_id) references water_fountains(fountain_id) on delete cascade
);

-- Helpers for the app's common reads.
create index idx_ratings_fountain   on ratings (fountain_id);
create index idx_visited_last_visit on user_visited (user_id, last_visited desc);
create index idx_fountains_name     on water_fountains (name);

