create table collectibles (
    collectible_id bigint generated by default as identity primary key,

    -- Every collectible belongs to a fountain (one-to-many). Deleting a fountain
    -- removes its collectibles, so there are never orphans.
    fountain_id    bigint not null references water_fountains(fountain_id) on delete cascade,

    name           text not null unique,
    image_path     text not null,              -- Storage key, e.g. 'collectibles/aldrich.png'
    rarity         text                        -- values decided later
);

create index idx_collectibles_fountain on collectibles (fountain_id);
create index idx_collectibles_rarity   on collectibles (rarity);

-- Public read; writes only via the backend/service role
alter table collectibles enable row level security;

create policy "collectibles are publicly readable"
    on collectibles for select
    to anon, authenticated
    using (true);
