-- Written reviews. The star rating for a review lives in `ratings` (same user + same fountain),
-- so this table only holds the text. One review per person per fountain.
create table if not exists reviews (
    review_id   bigint generated by default as identity primary key,
    user_id     bigint      not null references users(user_id)               on delete cascade,
    fountain_id bigint      not null references water_fountains(fountain_id) on delete cascade,
    body        text        not null,
    created_at  timestamptz not null default now(),
    constraint reviews_user_fountain_unique unique (user_id, fountain_id)
);

create index if not exists idx_reviews_fountain on reviews (fountain_id, created_at desc);
